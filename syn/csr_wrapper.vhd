library ieee;
use     ieee.std_logic_1164.all;
library asylum;
use     asylum.csr_pkg.all;

entity csr_wrapper is
  generic (
    WIDTH          : positive := 8;
    INIT           : std_logic_vector := "00000000";
    BLOCKING_READ  : boolean  := false;
    BLOCKING_WRITE : boolean  := true;
    DEPTH_SW2HW    : natural  := 0;
    DEPTH_HW2SW    : natural  := 0
  );
  port (
    clk_i               : in  std_logic;
    arst_b_i            : in  std_logic;

    -- csr_reg : 10 registers (one per software access model)
    reg_sw_wd_i         : in  std_logic_vector(10*WIDTH-1 downto 0);
    reg_sw_rd_o         : out std_logic_vector(10*WIDTH-1 downto 0);
    reg_sw_we_i         : in  std_logic_vector(10      -1 downto 0);
    reg_sw_re_i         : in  std_logic_vector(10      -1 downto 0);
    reg_sw_rbusy_o      : out std_logic_vector(10      -1 downto 0);
    reg_sw_wbusy_o      : out std_logic_vector(10      -1 downto 0);
    reg_hw_wd_i         : in  std_logic_vector(10*WIDTH-1 downto 0);
    reg_hw_rd_o         : out std_logic_vector(10*WIDTH-1 downto 0);
    reg_hw_we_i         : in  std_logic_vector(10      -1 downto 0);
    reg_hw_sw_re_o      : out std_logic_vector(10      -1 downto 0);
    reg_hw_sw_we_o      : out std_logic_vector(10      -1 downto 0);

    -- csr_ext
    ext_sw_wd_i         : in  std_logic_vector(WIDTH-1 downto 0);
    ext_sw_rd_o         : out std_logic_vector(WIDTH-1 downto 0);
    ext_sw_we_i         : in  std_logic;
    ext_sw_re_i         : in  std_logic;
    ext_sw_rbusy_o      : out std_logic;
    ext_sw_wbusy_o      : out std_logic;
    ext_hw_wd_i         : in  std_logic_vector(WIDTH-1 downto 0);
    ext_hw_rd_o         : out std_logic_vector(WIDTH-1 downto 0);
    ext_hw_we_i         : in  std_logic;
    ext_hw_sw_re_o      : out std_logic;
    ext_hw_sw_we_o      : out std_logic;

    -- csr_fifo
    fifo_sw_wd_i        : in  std_logic_vector(WIDTH-1 downto 0);
    fifo_sw_rd_o        : out std_logic_vector(WIDTH-1 downto 0);
    fifo_sw_we_i        : in  std_logic;
    fifo_sw_re_i        : in  std_logic;
    fifo_sw_rbusy_o     : out std_logic;
    fifo_sw_wbusy_o     : out std_logic;
    fifo_hw_tx_valid_i  : in  std_logic;
    fifo_hw_tx_ready_o  : out std_logic;
    fifo_hw_tx_data_i   : in  std_logic_vector(WIDTH-1 downto 0);
    fifo_hw_tx_empty_o  : out std_logic;
    fifo_hw_tx_full_o   : out std_logic;
    fifo_hw_rx_valid_o  : out std_logic;
    fifo_hw_rx_ready_i  : in  std_logic;
    fifo_hw_rx_data_o   : out std_logic_vector(WIDTH-1 downto 0);
    fifo_hw_rx_empty_o  : out std_logic;
    fifo_hw_rx_full_o   : out std_logic
  );
end entity csr_wrapper;

architecture rtl of csr_wrapper is

  -- Software access models of csr_reg (MODEL generic)
  function MODELS (i : natural) return string is
  begin
    case i is
      when 0      => return "ro";
      when 1      => return "rw";
      when 2      => return "wo";
      when 3      => return "rw1c";
      when 4      => return "rw0c";
      when 5      => return "rw1s";
      when 6      => return "rw0s";
      when 7      => return "rsw1c";
      when 8      => return "rcw1s";
      when others => return "rsw0c";
    end case;
  end function MODELS;

begin

  gen_csr_reg : for i in 0 to 9
  generate
    ins_csr_reg : csr_reg
      generic map (
        WIDTH      => WIDTH
       ,INIT       => INIT
       ,MODEL      => MODELS(i)
      )
      port map (
        clk_i      => clk_i
       ,arst_b_i   => arst_b_i
       ,sw_wd_i    => reg_sw_wd_i   ((i+1)*WIDTH-1 downto i*WIDTH)
       ,sw_rd_o    => reg_sw_rd_o   ((i+1)*WIDTH-1 downto i*WIDTH)
       ,sw_we_i    => reg_sw_we_i   (i)
       ,sw_re_i    => reg_sw_re_i   (i)
       ,sw_rbusy_o => reg_sw_rbusy_o(i)
       ,sw_wbusy_o => reg_sw_wbusy_o(i)
       ,hw_wd_i    => reg_hw_wd_i   ((i+1)*WIDTH-1 downto i*WIDTH)
       ,hw_rd_o    => reg_hw_rd_o   ((i+1)*WIDTH-1 downto i*WIDTH)
       ,hw_we_i    => reg_hw_we_i   (i)
       ,hw_sw_re_o => reg_hw_sw_re_o(i)
       ,hw_sw_we_o => reg_hw_sw_we_o(i)
      );
  end generate gen_csr_reg;

  ins_csr_ext : csr_ext
    generic map (
      WIDTH      => WIDTH
    )
    port map (
      clk_i      => clk_i
     ,arst_b_i   => arst_b_i
     ,sw_wd_i    => ext_sw_wd_i
     ,sw_rd_o    => ext_sw_rd_o
     ,sw_we_i    => ext_sw_we_i
     ,sw_re_i    => ext_sw_re_i
     ,sw_rbusy_o => ext_sw_rbusy_o
     ,sw_wbusy_o => ext_sw_wbusy_o
     ,hw_wd_i    => ext_hw_wd_i
     ,hw_rd_o    => ext_hw_rd_o
     ,hw_we_i    => ext_hw_we_i
     ,hw_sw_re_o => ext_hw_sw_re_o
     ,hw_sw_we_o => ext_hw_sw_we_o
    );

  ins_csr_fifo : csr_fifo
    generic map (
      WIDTH          => WIDTH
     ,BLOCKING_READ  => BLOCKING_READ
     ,BLOCKING_WRITE => BLOCKING_WRITE
     ,DEPTH_SW2HW    => DEPTH_SW2HW
     ,DEPTH_HW2SW    => DEPTH_HW2SW
    )
    port map (
      clk_i          => clk_i
     ,arst_b_i       => arst_b_i
     ,sw_wd_i        => fifo_sw_wd_i
     ,sw_rd_o        => fifo_sw_rd_o
     ,sw_we_i        => fifo_sw_we_i
     ,sw_re_i        => fifo_sw_re_i
     ,sw_rbusy_o     => fifo_sw_rbusy_o
     ,sw_wbusy_o     => fifo_sw_wbusy_o
     ,hw_tx_valid_i  => fifo_hw_tx_valid_i
     ,hw_tx_ready_o  => fifo_hw_tx_ready_o
     ,hw_tx_data_i   => fifo_hw_tx_data_i
     ,hw_tx_empty_o  => fifo_hw_tx_empty_o
     ,hw_tx_full_o   => fifo_hw_tx_full_o
     ,hw_rx_valid_o  => fifo_hw_rx_valid_o
     ,hw_rx_ready_i  => fifo_hw_rx_ready_i
     ,hw_rx_data_o   => fifo_hw_rx_data_o
     ,hw_rx_empty_o  => fifo_hw_rx_empty_o
     ,hw_rx_full_o   => fifo_hw_rx_full_o
    );

end architecture rtl;
