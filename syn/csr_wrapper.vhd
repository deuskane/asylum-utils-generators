-- Description:
-- Wrapper (lint_ghdl, lint_ghdl_synth_*) of the regtool building
-- blocks (tools/regtool/hdl) with flat and constrained ports (csr_reg has
-- generics without default and cannot be a top) :
--  * one csr_reg per software access model (MODELS below), register i on
--    the bits (i+1)*WIDTH-1 downto i*WIDTH (or bit i) of the reg_* ports,
--    reset value INIT
--  * one csr_ext (ext_* ports)
--  * one csr_fifo (fifo_* ports), generics forwarded
-- Components from csr_pkg, as in the CSR banks generated by regtool.
-- INIT is unconstrained (length WIDTH) : with GHDL 6.0.0, the
-- override (-g) of a generic whose subtype depends on another generic
-- fails at elaboration (NULL access) when it is forwarded to an instance.
